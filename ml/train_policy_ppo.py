"""PPO on the recorded self-play games: the policy-gradient step done properly.

Why a separate file: `train_policy_ce.py` is running in the night pipeline and must not change under it. This one keeps
the same data pipeline, model architecture and export, and replaces the loss:

  advantage  A(s,a) = outcome - V(s)          (V from --adv-value-model, the critic we already train; one outcome per
                                               game, so the terminal return is the only reward there is)
  ratio      r = exp(log pi_new(a|s) - log pi_old(a|s))     (pi_old = the --prev bundle, i.e. the model that PLAYED
                                               these games, so the ratio is exact rather than approximated)
  loss       -min(r A, clip(r, 1-eps, 1+eps) A) + entropy_bonus * H(pi_new)

The three things the one-line advantage weighting of 2026-11-14 was missing: the clipping (so a single pass cannot drag
the policy far), the per-batch normalisation of A (variance), and the entropy term (exploration). It still trains on
on-policy data generated by the model it started from, which is the point.

    py -3 ml/train_policy_ppo.py --data DIR --out BUNDLE --prev BUNDLE --adv-value-model VALUE_DIR
                                [--epochs 3] [--clip 0.2] [--entropy 0.01] [--rows-per-game 8]
"""
import argparse
import json
import os
import shutil
import sys
import time

import numpy as np
import torch
from torch import nn

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ares_data  # noqa: E402
from phase_model import export_from_arrays, load_exported  # noqa: E402
from train_policy_ce import CATEGORICAL, Head, cap_per_game, load_value_params, value_of  # noqa: E402

CLIP = 5.0


def load_type(directory, decision, rows_per_game, max_chunks, seed):
    rng = np.random.default_rng(seed)
    files = ares_data.chunk_paths(directory, decision)
    if max_chunks and len(files) > max_chunks:
        # Sample the chunks instead of taking the first N: with a wide iteration (tens of thousands of games) the first N
        # thousand games are one part of the run, not a sample of it.
        picked = np.random.default_rng(seed).choice(len(files), max_chunks, replace=False)
        files = [files[i] for i in sorted(picked)]
    obs, cands, chosen, count, outcome, game = [], [], [], [], [], []
    for path in files:
        schema, rows = ares_data.read_decisions(path)
        if not len(rows):
            continue
        if rows_per_game:
            keep = cap_per_game(rows["game"].astype(np.uint64), rows_per_game, rng)
            rows = rows[keep]
            if not len(rows):
                continue
        obs.append(rows["obs"].astype(np.float32))
        cands.append(rows["feat"].astype(np.float32))
        chosen.append(rows["chosen"].astype(np.int64))
        count.append(rows["count"].astype(np.int64))
        outcome.append(rows["outcome"].astype(np.float32))
        game.append(rows["game"].astype(np.uint64))
    if not obs:
        return None
    data = {"obs": np.concatenate(obs), "cands": np.concatenate(cands), "chosen": np.concatenate(chosen),
            "count": np.concatenate(count), "outcome": np.concatenate(outcome), "game": np.concatenate(game),
            "obsSize": schema["obsSize"], "candFeatures": schema["candidateFeatures"], "schemaHash": schema["hash"]}
    keep = data["count"] >= 2
    for key in ("obs", "cands", "chosen", "count", "outcome", "game"):
        data[key] = data[key][keep]
    return data


def load_into(model, bundle, decision, device):
    """Copy the parent's weights into `model` (observation columns padded when the encoder grew)."""
    meta, params = load_exported(os.path.join(bundle, decision))
    with torch.no_grad():
        old = params["mean"].shape[0]
        new = model.obs_layer.in_features
        model.obs_layer.weight.zero_()
        model.obs_layer.weight[:, :min(old, new)].copy_(torch.as_tensor(params["w_obs"])[:, :min(old, new)])
        model.obs_layer.bias.copy_(torch.as_tensor(params["b_obs"]))
        model.mean.zero_()
        model.mean[:old].copy_(torch.as_tensor(params["mean"]))
        model.std.fill_(1.0)
        model.std[:old].copy_(torch.as_tensor(params["std"]))
        model.cand_layer.weight.copy_(torch.as_tensor(params["w_cand"]))
        model.mid.weight.copy_(torch.as_tensor(params["w_mid"]))
        model.mid.bias.copy_(torch.as_tensor(params["b_mid"]))
        model.out.weight.copy_(torch.as_tensor(params["w_out"]).reshape(1, -1))
        model.out.bias.copy_(torch.as_tensor(params["b_out"]).reshape(-1)[:1])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--prev", required=True, help="the bundle that PLAYED this data (the old policy of the ratio)")
    parser.add_argument("--adv-value-model", required=True, help="critic: V(s), exported value_mlp folder")
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--rows-per-game", type=int, default=8)
    parser.add_argument("--max-chunks-per-type", type=int, default=16)
    parser.add_argument("--clip", type=float, default=0.2)
    parser.add_argument("--behaviour-temperature", type=float, default=1.0,
                        help="the temperature the data-generating player sampled with (selfplay.temperature). The ratio is "
                             "computed against THAT behaviour policy, so exploration data is corrected correctly")
    parser.add_argument("--entropy", type=float, default=0.01)
    parser.add_argument("--lr", type=float, default=1e-4)
    parser.add_argument("--batch", type=int, default=512)
    parser.add_argument("--val-fraction", type=float, default=0.1)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--types", default="")
    parser.add_argument("--device", default="auto")
    args = parser.parse_args()

    started = time.time()
    torch.manual_seed(args.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    decisions = [t for t in (args.types.split(",") if args.types else CATEGORICAL) if t]
    hidden = [256, 128]

    pools, val_pools, old_models, models = {}, {}, {}, {}
    for decision in decisions:
        data = load_type(args.data, decision, args.rows_per_game, args.max_chunks_per_type, args.seed)
        if data is None or len(data["obs"]) < 100:
            continue
        split_key = (data["game"] * np.uint64(2654435761)) % np.uint64(1000)
        val = split_key < int(1000 * args.val_fraction)
        pools[decision] = {k: (v[~val] if isinstance(v, np.ndarray) and len(v) == len(val) else v) for k, v in data.items()}
        val_pools[decision] = {k: (v[val] if isinstance(v, np.ndarray) and len(v) == len(val) else v) for k, v in data.items()}
        hidden = data.get("hidden", hidden)
        model = Head(data["obsSize"], data["candFeatures"], hidden).to(device)
        old = Head(data["obsSize"], data["candFeatures"], hidden).to(device)
        if args.prev:
            load_into(model, args.prev, decision, device)
            load_into(old, args.prev, decision, device)
        else:
            # No parent (e.g. the pipeline's smoke run): train from the initial weights, with the same weights as the
            # "old" policy, so the ratio starts at 1 and the first step is a plain policy gradient.
            old.load_state_dict(model.state_dict())
        old.eval()
        for p in old.parameters():
            p.requires_grad = False
        models[decision], old_models[decision] = model, old
        print(f"  {decision:22s} train {len(pools[decision]['obs']):7d}  val {len(val_pools[decision]['obs']):6d}  "
              f"candidates {data['cands'].shape[1]}")

    if not models:
        raise SystemExit("no usable decision types")

    critic = {k: torch.as_tensor(v if np.ndim(v) else float(v), dtype=torch.float32, device=device)
              for k, v in load_value_params(args.adv_value_model).items()}
    critic["clip"] = float(critic["clip"])
    optimizers = {d: torch.optim.Adam(models[d].parameters(), lr=args.lr) for d in models}
    rng = np.random.default_rng(args.seed)

    def log_probs(model, obs, cands, count, temperature=1.0):
        logits = model(obs, cands)
        mask = torch.arange(cands.shape[1], device=device)[None, :] < count[:, None]
        logits = logits.masked_fill(~mask, -1e9)
        return torch.log_softmax(logits / max(temperature, 1e-3), dim=1)

    def batches(data, indices):
        for start in range(0, len(indices), args.batch):
            idx = indices[start:start + args.batch]
            if len(idx) < 2:
                continue
            yield (torch.from_numpy(data["obs"][idx]).to(device),
                   torch.from_numpy(data["cands"][idx]).to(device),
                   torch.from_numpy(data["chosen"][idx]).to(device),
                   torch.from_numpy(data["count"][idx]).to(device),
                   torch.from_numpy(data["outcome"][idx]).to(device))

    history = []
    for epoch in range(1, args.epochs + 1):
        for decision, model in models.items():
            model.train()
            data = pools[decision]
            order = rng.permutation(len(data["obs"]))
            running, seen, clipped, entropy_sum = 0.0, 0, 0, 0.0
            for obs, cands, chosen, count, outcome in batches(data, order):
                with torch.no_grad():
                    old_log = log_probs(old_models[decision], obs, cands, count, args.behaviour_temperature)
                    old_taken = old_log.gather(1, chosen.unsqueeze(1)).squeeze(1)
                    advantage = outcome - value_of(obs, critic)
                    advantage = (advantage - advantage.mean()) / (advantage.std() + 1e-6)
                new_log = log_probs(model, obs, cands, count)
                new_taken = new_log.gather(1, chosen.unsqueeze(1)).squeeze(1)
                ratio = torch.exp(new_taken - old_taken)
                unclipped = ratio * advantage
                limited = torch.clamp(ratio, 1 - args.clip, 1 + args.clip) * advantage
                entropy = -(new_log.exp() * new_log).sum(dim=1).mean()
                loss = -torch.min(unclipped, limited).mean() - args.entropy * entropy
                if not torch.isfinite(loss):
                    raise SystemExit(f"{decision}: loss {float(loss)} in epoch {epoch}")
                optimizers[decision].zero_grad()
                loss.backward()
                nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                optimizers[decision].step()
                running += float(loss) * len(obs)
                seen += len(obs)
                clipped += int(((ratio - 1).abs() > args.clip).sum())
                entropy_sum += float(entropy) * len(obs)
            model.eval()
            with torch.no_grad():
                val = val_pools[decision]
                correct = total = 0
                for obs, cands, chosen, count, _ in batches(val, np.arange(len(val["obs"]))):
                    ranked = torch.topk(log_probs(model, obs, cands, count), 1, dim=1).indices.squeeze(1)
                    correct += int((ranked == chosen).sum())
                    total += len(obs)
            row = {"epoch": epoch, "type": decision, "loss": running / max(seen, 1),
                   "clip_fraction": clipped / max(seen, 1), "entropy": entropy_sum / max(seen, 1),
                   "agree_old": correct / max(total, 1)}
            history.append(row)
            print(json.dumps({k: (round(v, 4) if isinstance(v, float) else v) for k, v in row.items()}), flush=True)

    # export: parent bundle with the PPO-trained heads
    os.makedirs(args.out, exist_ok=True)
    if args.prev:
        for name in sorted(os.listdir(args.prev)):
            source = os.path.join(args.prev, name)
            if os.path.isdir(source) and name not in models:
                target = os.path.join(args.out, name)
                if not os.path.exists(target):
                    shutil.copytree(source, target)
            elif name in ("DONE", "MODEL_INFO.json"):
                shutil.copy2(source, os.path.join(args.out, name))
    for decision, model in models.items():
        state = model.state_dict()
        params = {"mean": state["mean"].cpu().numpy(), "std": state["std"].cpu().numpy(),
                  "w_obs": state["obs_layer.weight"].cpu().numpy(), "b_obs": state["obs_layer.bias"].cpu().numpy(),
                  "w_cand": state["cand_layer.weight"].cpu().numpy(),
                  "w_mid": state["mid.weight"].cpu().numpy(), "b_mid": state["mid.bias"].cpu().numpy(),
                  "w_out": state["out.weight"].cpu().numpy().reshape(-1), "b_out": state["out.bias"].cpu().numpy()}
        data = pools[decision]
        with torch.no_grad():
            val = val_pools[decision]
            sample = np.arange(min(8, len(val["obs"])))
            logits = model(torch.from_numpy(val["obs"][sample]).to(device),
                           torch.from_numpy(val["cands"][sample]).to(device)).cpu().numpy()
        reference = {"inputs": val["obs"][sample].tolist(), "candidates": val["cands"][sample].tolist(),
                     "logits": logits.tolist()}
        export_from_arrays(os.path.join(args.out, decision), data["schemaHash"], data["obsSize"],
                           data["candFeatures"], hidden, CLIP, params, reference, decision_type=decision)
    metrics = {"data": args.data, "prev": args.prev, "critic": args.adv_value_model, "types": list(models),
               "epochs": args.epochs, "clip": args.clip, "entropy": args.entropy, "lr": args.lr,
               "history": history, "seconds": round(time.time() - started, 1)}
    json.dump(metrics, open(os.path.join(args.out, "ppo_metrics.json"), "w", encoding="utf-8"), indent=1)
    with open(os.path.join(args.out, "DONE"), "w", encoding="utf-8") as f:
        f.write(json.dumps({"time": time.strftime("%Y-%m-%dT%H:%M:%S"), "trainer": "train_policy_ppo"}))
    print(json.dumps({k: v for k, v in metrics.items() if k != "history"}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
